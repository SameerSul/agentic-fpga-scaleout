def write_w8(work):
    """The DDR image: each 16-bit lane's low byte, int8, 16 to a word. In
    weights.bin lane j's low byte is every other byte, so this is a
    slice, and the byte order $fread reads is kept."""
    words = os.path.getsize(os.path.join(work, "weights.bin")) // 32
    w8 = os.path.join(work, "weights8.bin")
    if not os.path.exists(w8) or os.path.getsize(w8) != words * 16:
        with open(os.path.join(work, "weights.bin"), "rb") as f, \
                open(w8, "wb") as g:
            while True:
                blk = f.read(32 << 20)
                if not blk:
                    break
                g.write(blk[1::2])
    return w8


def layout(work, base=0):
    """Where each region sits in DDR, from a qwen_full.py build: the int8
    weights from base, then the column constants and the K and V caches,
    each on a 4 KB boundary. Addresses are absolute bus addresses."""
    core = open(os.path.join(work, "qwen_full.v")).read()
    old = open(os.path.join(work, "tb_qfull.v")).read()
    size = lambda name: int(re.search(r"%s \[0:(\d+)\]" % name, old).group(1)) + 1
    L = dict(W=widths(core), cn=size("cmem"), gn=size("gmem"),
             kn=size("km"), vn=size("vm"),
             words=os.path.getsize(os.path.join(work, "weights.bin")) // 32)
    align = lambda x: (x + 4095) // 4096 * 4096
    L["wb"] = base
    L["cb"] = align(base + L["words"] * 16)
    L["kb"] = align(L["cb"] + L["cn"] * 8)
    L["vb"] = align(L["kb"] + L["kn"] * 32)
    L["end"] = align(L["vb"] + L["vn"] * 32)
    L["steps"] = [tuple(int(v) for v in re.findall(r"-?\d+", l))
                  for l in old.splitlines() if l.strip().startswith("step(")]
    return L


def tb_text(L, np_, lat, dut=DUT, step=STEP, fs="dut.fs", jit=0):
    wd, wc, wr = render_tb_weights(np_, lat, L["wb"])
    W = L["W"]
    return TB % dict(twm=W["tok"] - 1, pwm=W["pos"] - 1, cn=L["cn"] - 1,
                     kn=L["kn"] - 1, vn=L["vn"] - 1, wb=L["wb"], cb=L["cb"],
                     kb=L["kb"], vb=L["vb"], lat=lat, wdecl=wd, jit=jit,
                     wresp=wr, dut=dut % dict(wconn=wc), step=step, fs=fs,
                     steps="\n".join("    step(%d, %d, %d);" % s
                                     for s in L["steps"]))


def simulate(work, tb, top_srcs):
    """Compile tb with the build's blocks and stream its output."""
    srcs = sorted(f for f in os.listdir(work) if f.endswith(".v")
                  and not f.startswith(("tb_", "bz_")) and f != "qwen_zybo.v")
    r = subprocess.run(["iverilog", "-g2005", "-DSIM", "-o", "z.out", tb]
                       + list(top_srcs) + srcs,
                       cwd=work, capture_output=True, text=True)
    if r.returncode:
        print(r.stdout[-3000:], r.stderr[-3000:])
        sys.exit(1)
    t0 = time.time()
    p = subprocess.Popen(["vvp", "z.out"], cwd=work, stdout=subprocess.PIPE,
                         text=True)
    for line in p.stdout:
        print(line.rstrip(), "(%.0f s)" % (time.time() - t0))
        sys.stdout.flush()
    p.wait()


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--work", default=os.path.join(ROOT, "build_qfull1"))
    ap.add_argument("--latency", type=int, default=30)
    ap.add_argument("--ports", type=int, default=4,
                    help="weight read masters; the Zynq-7000 has four HP ports")
    ap.add_argument("--jitter", action="store_true",
                    help="random ready stalls and gaps between beats")
    ap.add_argument("--base", type=lambda v: int(v, 0), default=0,
                    help="DDR address of the weights")
    a = ap.parse_args()
    work = a.work
    write_w8(work)
    L = layout(work, a.base)
    with open(os.path.join(work, "qwen_zybo.v"), "w") as f:
        f.write(render_top(L["W"], L["gn"], L["cb"], L["kb"], L["vb"],
                           a.ports, L["wb"]))
    with open(os.path.join(work, "tb_zybo.v"), "w") as f:
        f.write(tb_text(L, a.ports, a.latency, jit=int(a.jitter)))
    simulate(work, "tb_zybo.v", ["qwen_zybo.v"])


if __name__ == "__main__":
    main()
