"""Boards on their own clocks, splitting the model's layers: GALS.

Globally asynchronous, locally synchronous. Each board runs its stage,
a contiguous range of layers, on whatever clock it closes, and boards
share nothing but messages: the hidden state from one stage to the next,
and the chosen token back. No board waits on another's clock edge, so
any mix of boards works.

This is the link for boards without an ARM, the portable default: a
UART in the fabric on two pins, which any FPGA can build. (Zynq boards
carry the same messages over their ARM's Ethernet, see board_zybo.py.)
stage_ctrl sits beside each stage's sequencer. It receives a message,
checks its CRC32, loads a hidden state straight into the core, starts
it, and when the core is done sends the core's hidden state on, or, on
the last stage, the chosen token and its logit.

A message: A5 5A, type (1 token, 2 hidden state), position (2 bytes),
token (3 bytes), flags (bit 0: run the head), the payload (a token
message carries the logit, 2 bytes; a hidden-state message the vector,
2 bytes an element, low byte first), and the CRC32 of everything from
type on, as zlib computes it, low byte first.

The test runs the sequencer as two stages on unrelated clocks, 10 ns and
7.9 ns, whose UART dividers leave their bit times 1.25% apart, with a
host model at its own rate feeding the prompt and every generated token
back: the tokens and logits have to be one board's.

Run: python3 gals.py [--style qwen3]
"""
